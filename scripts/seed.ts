/**
 * Writes migrations/0002_seed_fixtures.sql from src/lib/estates/fixtures.ts, so a fresh D1
 * database serves the same six estates the mock did. Re-run after editing the fixtures:
 *
 *   bun run db:seed
 */
import { writeFileSync } from "node:fs";
import { ESTATES } from "../src/lib/estates/fixtures";

const q = (v: unknown) => `'${(typeof v === "string" ? v : JSON.stringify(v)).replaceAll("'", "''")}'`;
const now = Date.parse("2026-11-05T00:00:00Z");

const rows = ESTATES.map((e) =>
  [e.id, e.name, e.area, e.spec, e.price, e.travel, e.affinity, e.plan, e.map, e.photos, e.facts]
    .map((v, i) => (i === 4 ? String(v) : q(v)))
    .concat(String(now))
    .join(", "),
);

const sql = `-- Generated by scripts/seed.ts from src/lib/estates/fixtures.ts. Do not edit by hand.
INSERT INTO estates (id, name, area, spec, price, travel, affinity, plan, map, photos, facts, updated_at) VALUES
${rows.map((r) => `  (${r})`).join(",\n")};
`;

writeFileSync(new URL("../migrations/0002_seed_fixtures.sql", import.meta.url), sql);
console.log(`Wrote ${ESTATES.length} estates to migrations/0002_seed_fixtures.sql`);
